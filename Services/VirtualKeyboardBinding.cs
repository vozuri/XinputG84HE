    };

    public static KeyBinding Create(ushort rawKeyId, Profile profile, Func<uint, int>? mapScanCode = null)
    {
        // Preserve a VK learned from this device if this key is already assigned.
        var learned = profile.Bindings.Values.FirstOrDefault(b => b?.RawKeyId == rawKeyId && b.VirtualKey != 0);
        int vk = learned?.VirtualKey ?? rawKeyId switch
        {
            0x54 => 0x2C, // Print Screen
            0x5A => 0x13, // Pause
            0x47 => 0,    // Fn is handled by keyboard firmware; there is no Windows VK.
            _ => (mapScanCode ?? MapScanCode)(ScanCodes[rawKeyId]),
        };
        return new KeyBinding(rawKeyId, vk, KnownKeyNames.GetName(rawKeyId));
    }

    private static int MapScanCode(uint scanCode) =>
        (int)MapVirtualKeyExW(scanCode, 3 /* MAPVK_VSC_TO_VK_EX */, GetKeyboardLayout(0));

    [DllImport("user32.dll", ExactSpelling = true)]
    private static extern uint MapVirtualKeyExW(uint code, uint mapType, IntPtr keyboardLayout);

    [DllImport("user32.dll", ExactSpelling = true)]
    private static extern IntPtr GetKeyboardLayout(uint threadId);
}
